// Map of all language presets for fast bidirectional lookup
const ALL_CONTENT_PRESETS: LocalizedLegalContent[] = [
  CONTENT_HINDI,
  CONTENT_MARATHI,
  CONTENT_TAMIL,
  CONTENT_TELUGU,
  CONTENT_BENGALI,
  CONTENT_GUJARATI,
  CONTENT_KANNADA,
  CONTENT_MALAYALAM,
];

export function getAllPresetSituationPrompts(): Set<string> {
  const set = new Set<string>();
  for (const item of COMMON_SITUATIONS) {
    if (item.prompt) set.add(item.prompt.trim());
  }
  for (const content of ALL_CONTENT_PRESETS) {
    for (const item of content.commonSituations) {
      if (item.prompt) set.add(item.prompt.trim());
    }
  }
  return set;
}

export function getPresetIndex(prompt: string): number {
  if (!prompt || !prompt.trim()) return -1;
  const target = prompt.trim();

  // Check English
  const enIdx = COMMON_SITUATIONS.findIndex(
    (s) => s.prompt.trim() === target || target.includes(s.prompt.slice(0, 30))
  );
  if (enIdx >= 0) return enIdx;

  // Check all localized presets
  for (const content of ALL_CONTENT_PRESETS) {
    const idx = content.commonSituations.findIndex(
      (s) => s.prompt.trim() === target || target.includes(s.prompt.slice(0, 25))
    );
    if (idx >= 0) return idx;
  }

  return -1;
}

export function getCompleteLocalizedLegalData(
  language: string
): LocalizedLegalContent {
  const isMarathiOrKonkani = /Marathi|मराठी|Konkani|कोंकणी/i.test(language);
  const isTamil = /Tamil|தமிழ்/i.test(language);
  const isTelugu = /Telugu|తెలుగు/i.test(language);
  const isBengaliOrAssamese =
    /Bengali|বাংলা|Assamese|অসমীয়া|Manipuri|মৈতৈলোন্/i.test(language);
  const isGujarati = /Gujarati|ગુજરાતી/i.test(language);
  const isKannadaOrTulu = /Kannada|ಕನ್ನಡ|Tulu|ತುಳು/i.test(language);
  const isMalayalam = /Malayalam|മലയാളം/i.test(language);

  if (isMarathiOrKonkani) return CONTENT_MARATHI;
  if (isTamil) return CONTENT_TAMIL;
  if (isTelugu) return CONTENT_TELUGU;
  if (isBengaliOrAssamese) return CONTENT_BENGALI;
  if (isGujarati) return CONTENT_GUJARATI;
  if (isKannadaOrTulu) return CONTENT_KANNADA;
  if (isMalayalam) return CONTENT_MALAYALAM;

  const isHindiOrDevanagari =
    /Hindi|हिन्दी|Maithili|मैथिली|Bhojpuri|भोजपुरी|Rajasthani|राजस्थानी|Haryanvi|हरियाणवी|Chhattisgarhi|छत्तीसगढ़ी|Sanskrit|संस्कृत|Kashmiri|कश्मीरी|Nepali|नेपाली|Sindhi|सिन्धी|Dogri|डोगरी|Bodo|बर'|Garhwali|गढ़वाली|Kumaoni|कुमाऊँनी|Santali|Punjabi|ਪੰਜਾਬੀ|Odia|ଓଡ଼ିଆ|Urdu|اردو/i.test(
      language
    );

  if (isHindiOrDevanagari) return CONTENT_HINDI;

  return {
    commonSituations: COMMON_SITUATIONS,
    initialAssessment: INITIAL_ASSESSMENT,
    milestones: INITIAL_MILESTONES,
    evidenceItems: EVIDENCE_ITEMS,
    eligibilityCategories: ELIGIBILITY_CATEGORIES,
    lawLibraryTopics: LAW_LIBRARY_TOPICS,
    citizenFaqs: CITIZEN_FAQS,
  };
}
